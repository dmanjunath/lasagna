// How an .svg file becomes the string constant in generated.ts. Shared by the
// generator script and the test that checks the two are in sync.

export const MASCOT_NAMES = ["happy", "sleepy"] as const;
export type MascotName = (typeof MASCOT_NAMES)[number];

/** Drops comments and collapses whitespace, so the string is small and any SVG parser takes it. */
export function compactSvg(svg: string): string {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/>\s+</g, "><")
    .replace(/\s+/g, " ")
    .trim();
}

export function renderMascotModule(sources: Record<string, string>): string {
  const lines = MASCOT_NAMES.map((n) => `export const ${n} = ${JSON.stringify(compactSvg(sources[n]))};`);
  return `// Generated by scripts/gen-mascot.ts from the .svg files in this folder. Do not edit.\n${lines.join("\n")}\n`;
}
