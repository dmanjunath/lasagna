import { describe, it, expect, vi, beforeEach } from "vitest";

/**
 * Actions belong to a step of the path.
 *
 * Two properties carry this slice, and both are asserted here against the real
 * generation path rather than against a helper:
 *
 *  1. A step key the model invented, or one that names a step this person is
 *     not on, is dropped to NO step. It is never persisted, because a stored
 *     key nothing answers to would put the action under a heading that does not
 *     exist. The action itself is kept either way.
 *  2. The reference is the path's own candidate key, not a step ROW. A path is
 *     regenerated by superseding its steps and inserting a fresh set, so a row
 *     id would come loose on every rebuild and take every action's place in the
 *     plan with it. The regeneration test below is the one that proves it.
 */

